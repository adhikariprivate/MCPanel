// Msg is a message in a language, English when the language or the key is missing. Every argument that is text from outside (a
// name, an address, an error) must be passed through Escape first.
func Msg(lang, key string, args ...any) string {
	m, ok := messages[lang][key]
	if !ok {
		m = messages["en"][key]
	}
	return fmt.Sprintf(m, args...)
}
